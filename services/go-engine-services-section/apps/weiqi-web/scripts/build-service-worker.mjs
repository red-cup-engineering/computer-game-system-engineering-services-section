// Writes public/sw.js: the service worker that makes the site installable
// and keeps study content available offline. The precache list is every
// file under public/ (except the worker itself), and the cache name is a
// digest of their contents, so each build gets its own cache and activation
// drops the previous one. BUILD PRODUCT: never hand-edit public/sw.js.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const PUBLIC = fileURLToPath(new URL("../public/", import.meta.url));

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) return walk(path);
    return [path];
  }));
  return files.flat();
}

const files = (await walk(PUBLIC))
  .map((path) => "/" + relative(PUBLIC, path).split(sep).join("/"))
  .filter((path) => path !== "/sw.js" && !path.includes("/.") )
  .sort();
const digest = createHash("sha256");
// Cache identity includes the receiving policy, not only its payload files.
digest.update(await readFile(fileURLToPath(import.meta.url)));
for (const path of files) {
  digest.update(path);
  digest.update(await readFile(resolve(PUBLIC, path.slice(1))));
}
const version = digest.digest("base64url").slice(0, 16);

const source = `// @generated by scripts/build-service-worker.mjs; DO NOT EDIT.
// Network first, cache fallback: online visitors always get the deployed
// bytes; offline visitors get the last build this worker precached. The
// match API is never cached.
const CACHE = "weiqi-web-${version}";
const PRECACHE = ${JSON.stringify(files, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

function cacheKeyFor(request) {
  const url = new URL(request.url);
  if (url.pathname.endsWith("/")) url.pathname += "index.html";
  else if (PRECACHE.includes(url.pathname + ".html")) url.pathname += ".html";
  else if (PRECACHE.includes(url.pathname + "/index.html")) url.pathname += "/index.html";
  url.search = "";
  url.hash = "";
  return url.href;
}

// Precache follows the host's clean-URL redirects. A navigation request uses
// manual redirects, so a cached response carrying redirect history cannot be
// returned as its page. Preserve the received body and headers as a fresh
// response; resources retain their response URL for module-relative imports.
function cachedResponse(response, request) {
  if (request.mode !== "navigate" || !response.redirected) return response;
  return new Response(response.body, {
    status: response.status, statusText: response.statusText, headers: response.headers,
  });
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const key = cacheKeyFor(request);
    try {
      const response = await fetch(request);
      if (response.ok) cache.put(key, response.clone());
      return response;
    } catch (error) {
      const cached = await cache.match(key);
      if (cached) return cachedResponse(cached, request);
      if (request.mode === "navigate") {
        const home = await cache.match(self.location.origin + "/index.html");
        if (home) return cachedResponse(home, request);
      }
      throw error;
    }
  })());
});
`;
await writeFile(resolve(PUBLIC, "sw.js"), source, "utf8");
console.log(`Wrote public/sw.js precaching ${files.length} files as ${"weiqi-web-" + version}`);
